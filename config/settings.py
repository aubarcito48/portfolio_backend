from pathlib import Path
import os

from django.core.exceptions import ImproperlyConfigured
from dotenv import load_dotenv

# Build paths inside the project like this: BASE_DIR / 'subdir'.
BASE_DIR = Path(__file__).resolve().parent.parent

load_dotenv(BASE_DIR / '.env')

ENVIRONMENT = os.getenv('DJANGO_ENVIRONMENT', 'development').strip().lower()
if ENVIRONMENT not in {'development', 'test', 'production'}:
    raise ImproperlyConfigured(
        'DJANGO_ENVIRONMENT debe ser development, test o production.'
    )

SECRET_KEY = os.getenv('DJANGO_SECRET_KEY')
if not SECRET_KEY:
    raise ImproperlyConfigured(
        'Definí DJANGO_SECRET_KEY en el entorno o en el archivo .env.'
    )

debug_value = os.getenv('DJANGO_DEBUG')
if debug_value is None:
    DEBUG = ENVIRONMENT == 'development'
else:
    normalized_debug_value = debug_value.strip().lower()
    if normalized_debug_value not in {'true', 'false'}:
        raise ImproperlyConfigured(
            'DJANGO_DEBUG debe ser True o False.'
        )
    DEBUG = normalized_debug_value == 'true'

allowed_hosts = [
    host.strip()
    for host in os.getenv('DJANGO_ALLOWED_HOSTS', '').split(',')
    if host.strip()
]
if ENVIRONMENT == 'production' and not allowed_hosts:
    raise ImproperlyConfigured(
        'Definí DJANGO_ALLOWED_HOSTS explícitamente para producción.'
    )
if ENVIRONMENT == 'production' and DEBUG:
    raise ImproperlyConfigured(
        'DJANGO_DEBUG debe ser False en producción.'
    )

if not allowed_hosts and ENVIRONMENT == 'development':
    allowed_hosts = ['127.0.0.1', 'localhost']
elif not allowed_hosts and ENVIRONMENT == 'test':
    allowed_hosts = ['testserver', 'localhost']

ALLOWED_HOSTS = allowed_hosts


